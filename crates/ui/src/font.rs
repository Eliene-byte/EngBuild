//! A built-in stroke font.
//!
//! Rendering text needs *something* on the GPU. Options were a TTF parser plus
//! a rasteriser (about 15 kB of dependencies) or a bitmap atlas generated at
//! startup (a second pipeline, a sampler, a second bind group). A stroke font
//! needs neither: every glyph is a handful of polylines, and the existing
//! anti-aliased line pipeline draws them.
//!
//! Each glyph lives in a 4-wide by 6-tall box, `y` pointing down, with the
//! baseline at `y = 6`. [`Glyph::advance`] turns those units into pixels.
//!
//! Lowercase input folds to uppercase: the glyph set is upper-case-only, which
//! is a deliberate trade (a CAD status bar reads fine in caps, and the table
//! stays small enough to audit by eye).

/// Width of the glyph box in font units.
pub const UNITS_W: f32 = 4.0;
/// Height of the glyph box in font units (cap height).
pub const UNITS_H: f32 = 6.0;
/// Gap between glyph boxes, in font units.
pub const TRACKING: f32 = 2.0;

/// A glyph: one polyline per stroke, in font units.
pub struct Glyph {
    /// Advance width in font units, including [`TRACKING`].
    pub advance: f32,
    /// Strokes, each a list of `(x, y)` points in font units.
    pub strokes: &'static [&'static [(f32, f32)]],
}

/// Advance of a full-width glyph in font units.
const ADV: f32 = UNITS_W + TRACKING;

