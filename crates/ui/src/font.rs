/// Width in pixels of `s` when drawn at `size` (cap height in pixels).
///
/// `s` is measured the same way it is drawn, including lowercase folding and the
/// `?` fallback, so this is exact rather than an estimate.
pub fn measure(s: &str, size: f32) -> f32 {
    let unit = size / UNITS_H;
    s.chars().map(|c| glyph(c).advance * unit).sum()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_letter_and_digit_has_a_glyph() {
        for c in ('A'..='Z').chain('0'..='9') {
            assert!(
                !glyph(c).strokes.is_empty(),
                "{c} has no strokes and is not a space"
            );
        }
    }

    #[test]
    fn space_is_blank_but_still_advances() {
        let g = glyph(' ');
        assert!(g.strokes.is_empty());
        assert_eq!(g.advance, ADV);
        assert!(measure("a b", 12.0) > measure("ab", 12.0));
    }

    #[test]
    fn lowercase_folds_to_uppercase() {
        assert_eq!(glyph('a').strokes.len(), glyph('A').strokes.len());
        assert_eq!(glyph('q').strokes.len(), glyph('Q').strokes.len());
    }

    #[test]
    fn unknown_characters_fall_back_to_question_mark() {
        assert_eq!(glyph('\u{4e2d}').strokes.len(), glyph('?').strokes.len());
        assert_eq!(glyph('\u{4e2d}').advance, glyph('?').advance);
    }

    #[test]
    fn measure_is_additive_and_monotonic() {
        let one = measure("A", 12.0);
        assert!((measure("AA", 12.0) - one * 2.0).abs() < 1e-5);
        assert!((measure("A", 24.0) - one * 2.0).abs() < 1e-5);
        assert_eq!(measure("", 12.0), 0.0);
    }

    #[test]
    fn strokes_stay_inside_a_reasonable_box() {
        // Descenders (comma, underscore) are allowed to dip below the baseline;
        // nothing should fly off to infinity, which would mean a typo in the table.
        for c in ('A'..='Z').chain('0'..='9').chain(['_', ',', '|', '~']) {
            for stroke in glyph(c).strokes {
                for &(x, y) in stroke {
                    assert!(x.is_finite() && y.is_finite(), "{c}: ({x},{y})");
                    assert!((-1.0..=5.0).contains(&x), "{c}: x={x} out of range");
                    assert!((-1.0..=8.0).contains(&y), "{c}: y={y} out of range");
                }
            }
        }
    }
}
